import assert from 'node:assert/strict';
import { ActivityHistory, actuals, boardDay, dateLabel, mergeBoard } from '../web/board-activity.js';

const stamp = day => Date.UTC(2026, 10, day);
const day = n => boardDay(stamp(n));
assert.equal(dateLabel(boardDay(Date.UTC(2026, 10, 20, 15))), '2026-11-21');
const history = new ActivityHistory('fixture');
const event = (seq, n, kind, from, to) => ({ seq, item_id: 'item', at: stamp(n), kind, from, to });
const page = events => ({ history_epoch: 'fixture', events });
history.append(page([event(1, 12, 'state_change', 'planned', 'done'), event(2, 14, 'state_change', 'done', 'in_progress')]), 4);
assert.throws(() => history.append(page([event(2, 14, 'note')]), 4));
assert.throws(() => history.append({ history_epoch: 'other', events: [] }, 4));
history.append(page([event(3, 14, 'requested'), event(4, 15, 'accepted')]), 4);
const item = { state: 'in_progress', created_at: stamp(10), updated_at: stamp(20) };
const facts = actuals(item, history.items.get('item'), stamp(19));
assert.deepEqual(facts.periods, [{ start: day(10), end: day(12) }, { start: day(14), end: day(19), ongoing: true }]);
assert.deepEqual([...facts.days.get(day(14))], ['再開', '依頼']);
assert.ok(facts.days.get(day(15)).has('受理'));
const old = actuals({ ...item, state: 'stopped', handoff: { requested_at: stamp(11) } }, undefined, stamp(22));
assert.deepEqual(old.periods, []);
assert.equal(old.unknownEnd, true);
assert.equal(old.days.has(day(20)), false);
assert.ok(old.days.get(day(11)).has('依頼'));
const cached = { revision: 'x', items: [4, null].map(lease_until => ({ handoff: { state: 'accepted', lease_until, lease_expired: false } })) };
const refresh = generated_at => mergeBoard(cached, { revision: 'x', unchanged: true, generated_at });
assert.equal(refresh(4).items[0].handoff.lease_expired, false);
assert.deepEqual(refresh(5).items.map(i => i.handoff.lease_expired), [true, false]);
assert.throws(() => mergeBoard(cached, { unchanged: true, revision: 'other' }));
console.log('activity dates, historical periods and conditional leases passed');
